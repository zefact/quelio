/**
 * 実行の受付票。
 *
 * 実行ボタンを押した瞬間に、**押した画面**で作る。
 * どの接続タブの、どのデータベースの、どのシートに対する実行なのかを
 * ここに写し取り、実行し終わるまで持ち回る。
 *
 * 押してから実際に走るまでには、文の分割・危険判定・パラメータの準備という
 * 往復が入る。その間に利用者は別の接続タブへ切り替えられるし、
 * データベースやシートも選び直せる。
 * 「今どこを見ているか」で宛先を決めると、待っている間に切り替えただけで
 * 別の接続へSQLが渡ってしまう。
 *
 * 受付番号 (token) も接続タブごとの連番なので、番号だけでは足りない。
 * 別のタブの同じ番号と偶然一致してしまう。
 * どのタブの番号なのかを一緒に持って初めて、照合先が定まる
 */
import type { ReqSeq } from "./reqSeq";
import type { DbType } from "./types";

export interface RunTicket {
  /** 発行元の接続タブ */
  key: string;
  /** そのタブでの受付番号 */
  token: number;
  /** 押した時点で選んでいたデータベース */
  db: string | null;
  /** 押した時点のSQLシート (結果を返す先) */
  sheet: string;
  /*
   * ここから下は、実行前の確認画面に「どこへ実行するのか」を出すためのもの。
   *
   * 画面の今の値から取ると、確認が出るまでの間に別の接続へ切り替えただけで、
   * 見せている相手と実際に走る相手が食い違う。
   * 実行先と同じ受付票から取れば、必ず一致する
   */
  /** 発行元の接続名 */
  connection: string;
  /** 発行元のDB種別 (定義変更の注意文がこれで変わる) */
  dbType: DbType;
}

/** 受付番号の用途 (接続タブごとに分ける) */
export function runScope(key: string): string {
  return `${key}:run`;
}

/**
 * この受付票がまだ有効か。
 *
 * 照合先は必ず受付票の中のタブから決める。
 * 今表示しているタブから決めると、待っている間に切り替えただけで
 * 別のタブの番号と突き合わせることになる
 */
export function isCurrentRun(seq: ReqSeq, ticket: RunTicket): boolean {
  return seq.isLatest(runScope(ticket.key), ticket.token);
}
